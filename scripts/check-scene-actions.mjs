import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', args: ['--enable-unsafe-swiftshader'] });
try {
 const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
 const errors = []; page.on('pageerror', e => errors.push(e.message));
 await page.goto('http://localhost:3000/editor?scene=pavilion-v1');
 const add = page.getByRole('button', { name: 'Add scene', exact: true });
 await expect(add).toBeEnabled({ timeout: 60000 });
 await expect(page.getByRole('button', { name: 'Remove scene', exact: true })).toBeDisabled();
 await add.click();
 await page.getByRole('dialog', { name: 'Add scene', exact: true }).getByRole('button', { name: 'Barcelona Pavilion' }).click();
 await page.waitForURL(url => url.searchParams.has('project'));
 await expect(add).toBeEnabled({ timeout: 60000 });
 const id = new URL(page.url()).searchParams.get('project');
 const read = () => page.evaluate(id => JSON.parse(localStorage.getItem(`showcam-project:item:v1:${encodeURIComponent(id)}`)), id);
 let saved = await read();
 assert.equal(saved.scenes.length, 2);
 const firstId = saved.scenes[0].id;
 await expect(page.getByRole('combobox', { name: 'Scene', exact: true })).toHaveValue(saved.scenes[1].id);
 await page.getByRole('button', { name: 'Remove scene', exact: true }).click();
 await page.getByRole('dialog', { name: 'Remove scene', exact: true }).getByRole('button', { name: 'Cancel' }).click();
 assert.equal((await read()).scenes.length, 2);
 await page.getByRole('button', { name: 'Remove scene', exact: true }).click();
 await page.getByRole('dialog', { name: 'Remove scene', exact: true }).getByRole('button', { name: 'Remove scene', exact: true }).click();
 await page.waitForURL(url => url.searchParams.get('entry') === firstId);
 await expect(add).toBeEnabled({ timeout: 60000 });
 saved = await read(); assert.equal(saved.scenes.length, 1); assert.equal(saved.scenes[0].id, firstId);
 await page.reload();
 await expect(add).toBeEnabled({ timeout: 60000 });
 await expect(page.getByRole('button', { name: 'Remove scene', exact: true })).toBeDisabled();
 await page.setViewportSize({ width: 390, height: 844 });
 await add.click();
 const popup = page.getByRole('dialog', { name: 'Add scene', exact: true });
 await expect(popup).toBeVisible();
 const box = await popup.boundingBox(); assert.ok(box.x >= 0 && box.x + box.width <= 390);
 await page.screenshot({ path: '/private/tmp/scene-actions-mobile.png' });
 await page.keyboard.press('Escape'); await expect(popup).toHaveCount(0); await expect(add).toBeFocused();
 assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
 assert.deepEqual(errors, []);
 console.log('Scene addition, standalone migration, removal cancellation, removal persistence, last-scene guard, and mobile controls passed.');
} finally { await browser.close(); }
