import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

const base = (process.env.SHOWCAM_URL || 'http://localhost:3000').split('?')[0];
const dir = process.env.SHOWCAM_ARTIFACT_DIR || '.impeccable/review/collision';
await mkdir(dir, { recursive: true });
const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
const page = await context.newPage(); page.setDefaultTimeout(30000);
const errors = []; page.on('pageerror', e => errors.push(e.message));
const storageKey = 'showcam-project:v1:residence-9d09ab82';
const saved = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)), storageKey);
const ready = () => page.waitForSelector('canvas[data-ready="true"]', { timeout: 120000 });
const panel = page.getByRole('region', { name: 'Splat collision boxes' });
const status = panel.getByRole('status');
const shots = [];
try {
  await page.goto(base); await ready();
  await page.getByRole('button', { name: 'Project', exact: true }).click();
  await page.getByRole('button', { name: 'Generate around view', exact: true }).click();
  await expect(status).toContainText('Needs review', { timeout: 120000 });
  const generated = (await saved()).collision;
  assert.ok(generated.boxes.length > 0 && generated.boxes.length <= 400);
  assert.ok(generated.sampleCount > 0); assert.equal(generated.reviewed, false);
  assert.ok(generated.boxes.every(b => b.min.every((v, i) => v >= generated.region.min[i] && b.max[i] <= generated.region.max[i])));
  await page.getByRole('button', { name: 'Remove box', exact: true }).click();
  await expect(status).toContainText(`${generated.boxes.length - 1} boxes`);
  await page.getByRole('button', { name: 'Undo change', exact: true }).click();
  await expect(status).toContainText(`${generated.boxes.length} boxes`);
  await page.getByText('Adjust box bounds', { exact: true }).click();
  const minimum = await page.getByRole('spinbutton', { name: 'X min', exact: true }).inputValue();
  const maximum = await page.getByRole('spinbutton', { name: 'X max', exact: true }).inputValue();
  await page.getByRole('spinbutton', { name: 'X max', exact: true }).fill(minimum);
  await page.getByRole('button', { name: 'Apply bounds', exact: true }).click();
  await expect(panel.getByRole('alert')).toContainText('Invalid collision');
  assert.deepEqual((await saved()).collision.boxes, generated.boxes);
  await page.getByRole('spinbutton', { name: 'X max', exact: true }).fill(String(Number(maximum) - .01));
  await page.getByRole('button', { name: 'Apply bounds', exact: true }).click();
  await expect(panel.getByRole('alert')).toHaveCount(0);
  await page.getByText('Adjust box bounds', { exact: true }).click();
  await page.getByRole('button', { name: 'Use reviewed boxes', exact: true }).click();
  await expect(status).toContainText('Reviewed for this area');
  const reviewed = (await saved()).collision;
  assert.equal(reviewed.reviewed, true);
  await page.reload(); await ready();
  await page.getByRole('button', { name: 'Project', exact: true }).click();
  await expect(status).toContainText('Reviewed for this area');
  assert.deepEqual((await saved()).collision, reviewed);
  await page.getByRole('radio', { name: 'Camera', exact: true }).check();
  await expect(page.getByRole('region', { name: 'CinemaTraj path optimization' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Optimize drone path' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Create actor path' })).toBeEnabled();
  await page.getByRole('radio', { name: 'Project', exact: true }).check();
  await page.getByText('Generation settings', { exact: true }).click();
  await page.getByRole('spinbutton', { name: 'Review radius', exact: true }).fill('0');
  await page.getByRole('button', { name: 'Regenerate around view', exact: true }).click();
  await expect(panel.getByRole('alert')).toContainText('1–12');
  assert.deepEqual((await saved()).collision, reviewed, 'Failed generation preserves the previous reviewed layer');
  await page.getByRole('spinbutton', { name: 'Review radius', exact: true }).fill('4');
  // Remount controls to clear the deliberately tested validation message.
  await page.getByRole('radio', { name: 'Object', exact: true }).check();
  await page.getByRole('radio', { name: 'Project', exact: true }).check();
  await page.getByRole('button', { name: 'Return to review', exact: true }).click();
  await expect(status).toContainText('Needs review');
  await page.getByRole('checkbox', { name: 'Show collision boxes', exact: true }).check();
  await page.getByRole('combobox', { name: 'Review box', exact: true }).selectOption({ index: Math.floor(generated.boxes.length / 2) });
  await page.getByRole('checkbox', { name: 'Show only selected box', exact: true }).check();
  for (const [name, width, height] of [['desktop',1440,900], ['user-505',505,845], ['mobile',390,844]]) {
    await page.setViewportSize({ width, height });
    await status.scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: `${dir}/${name}.png`, fullPage: true }); shots.push(`${dir}/${name}.png`);
  }
  const formAudit = await new AxeBuilder({ page }).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
  assert.deepEqual(formAudit.violations.map(v => ({ id: v.id, impact: v.impact })), [], 'Open collision controls accessibility');
  await page.getByRole('button', { name: 'Frame box', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Object inspector' })).toHaveCount(0);
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await page.screenshot({ path: `${dir}/mobile-scene.png`, fullPage: true }); shots.push(`${dir}/mobile-scene.png`);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole('button', { name: 'Reset view', exact: true }).click();
  await page.getByRole('button', { name: 'Project', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Show only selected box', exact: true }).uncheck();
  await page.getByRole('button', { name: 'Show inspector', exact: true }).click();
  await page.screenshot({ path: `${dir}/desktop-scene.png`, fullPage: true }); shots.push(`${dir}/desktop-scene.png`);
  const audit = await new AxeBuilder({ page }).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
  assert.deepEqual(audit.violations.map(v => ({ id: v.id, impact: v.impact })), []);
  assert.deepEqual(errors, []);
  await writeFile(`${dir}/result.json`, JSON.stringify({ generated: { boxCount: generated.boxes.length, samples: generated.sampleCount, region: generated.region }, shots, errors, accessibility: { form: formAudit.violations, scene: audit.violations }, checks: ['real coarse splat decoding','bounded generation','review required','remove/undo','bounds validation/edit','approval','save/reload','CinemaTraj eligibility','failed generation preservation','review revocation','responsive overflow'] }, null, 2));
  console.log(`Collision E2E passed: ${generated.boxes.length} real generated boxes; review, edits, persistence, eligibility and responsive checks.`);
} finally { await browser.close(); }
