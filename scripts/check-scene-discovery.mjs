import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

const base = process.env.SHOWCAM_URL || 'http://localhost:3000';
const dir = process.env.SHOWCAM_ARTIFACT_DIR || '.agent-local/artifacts/scene-discovery';
await mkdir(dir, { recursive: true });
const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
const page = await context.newPage();
const errors = []; page.on('pageerror', error => errors.push(error.message));
page.setDefaultTimeout(30000);
const open = async () => { await page.goto(base); await page.getByRole('button', { name: 'New project', exact: true }).click(); };
try {
  await open();
  await expect(page.getByLabel('Project name', { exact: true })).toBeFocused();
  await expect(page.getByRole('button', { name: 'Create project', exact: true })).toBeDisabled();
  await page.getByLabel('Project name', { exact: true }).fill('SuperSplat garden test');
  await page.getByRole('button', { name: 'Greenhouse', exact: true }).click();
  const chosen = page.getByRole('button', { name: 'Choose Hozy Greenhouse', exact: true });
  await expect(chosen).toBeVisible(); await chosen.click();
  await expect(chosen).toHaveAttribute('aria-pressed', 'true');
  await page.evaluate(() => document.fonts.ready);
  await chosen.locator('img').evaluate(image => image.decode());
  await page.screenshot({ path: `${dir}/desktop.png` });
  const desktopAxe = await new AxeBuilder({ page }).include('dialog').analyze();
  await page.setViewportSize({ width: 390, height: 844 });
  await chosen.scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${dir}/phone.png` });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  const mobileAxe = await new AxeBuilder({ page }).include('dialog').analyze();
  await writeFile(`${dir}/accessibility.json`, JSON.stringify({ desktop: desktopAxe.violations, mobile: mobileAxe.violations }, null, 2));
  assert.deepEqual(desktopAxe.violations, []); assert.deepEqual(mobileAxe.violations, []);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Create project', exact: true }).click();
  await page.waitForURL(/\/editor\?scene=supersplat-592480a3-v1&project=/);
  const editorUrl = page.url();
  await page.waitForSelector('canvas[data-ready="true"]', { timeout: 120000 });
  assert.ok(Number(await page.locator('canvas').getAttribute('data-splats')) > 0);
  await expect(page.getByRole('heading', { name: 'Hozy Greenhouse', exact: true })).toBeVisible();
  await page.screenshot({ path: `${dir}/editor.png` });
  await page.reload();
  await page.waitForSelector('canvas[data-ready="true"]', { timeout: 120000 });
  await page.goto(base);
  await expect(page.getByRole('heading', { name: 'SuperSplat garden test', exact: true })).toBeVisible();
  assert.equal(await page.getByRole('link').filter({ has: page.getByRole('heading', { name: 'SuperSplat garden test', exact: true }) }).getAttribute('href'), editorUrl.replace(base, ''));

  // Deterministic recovery states, without depending on a remote outage.
  await page.getByRole('button', { name: 'New project', exact: true }).click();
  await page.route('**/api/scenes/search?*', route => route.fulfill({ json: { results: [] } }));
  await page.getByLabel('What kind of scene are you looking for?').fill('no-results');
  await page.getByLabel('What kind of scene are you looking for?').press('Enter');
  await expect(page.getByRole('status')).toContainText('No scenes found');
  await expect(page.getByRole('button', { name: 'Create project', exact: true })).toBeDisabled();
  await page.unroute('**/api/scenes/search?*');
  await page.route('**/api/scenes/search?*', route => route.fulfill({ status: 502, json: { error: 'SuperSplat is unavailable right now. Try again shortly or choose a built-in scene.' } }));
  await page.getByRole('button', { name: 'Find scenes', exact: true }).click();
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('SuperSplat is unavailable');
  await page.getByRole('button', { name: 'Built-in scenes', exact: true }).click();
  await expect(page.getByLabel('Starting scene')).toHaveValue('pavilion-v1');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByRole('button', { name: 'New project', exact: true })).toBeFocused();
  // Failed source validation must not leave an orphan saved project.
  const savedKeys = () => page.evaluate(() => Object.keys(localStorage).filter(key => key.startsWith('showcam-project:')).sort());
  const beforeKeys = await savedKeys();
  await page.unroute('**/api/scenes/search?*');
  const option = { id: 'supersplat-592480a3-v1', name: 'Test greenhouse', author: 'creator', sizeBytes: 16000000, license: 'by', thumbnailUrl: '', sourceUrl: 'https://superspl.at/scene/592480a3', description: '' };
  await page.route('**/api/scenes/search?*', route => route.fulfill({ json: { results: [option] } }));
  await page.route('**/api/scenes/manifest?*', route => route.fulfill({ status: 502, json: { error: 'This scene changed. Search again.' } }));
  await page.getByRole('button', { name: 'New project', exact: true }).click();
  await page.getByLabel('Project name', { exact: true }).fill('Do not save');
  await page.getByLabel('What kind of scene are you looking for?').fill('greenhouse');
  await page.getByRole('button', { name: 'Find scenes', exact: true }).click();
  await page.getByRole('button', { name: 'Choose Test greenhouse', exact: true }).click();
  await page.getByRole('button', { name: 'Create project', exact: true }).click();
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('This scene changed');
  assert.deepEqual(await savedKeys(), beforeKeys);
  await page.getByLabel('What kind of scene are you looking for?').fill('library');
  await expect(page.getByRole('button', { name: 'Create project', exact: true })).toBeDisabled();
  await page.keyboard.press('Escape');
  assert.deepEqual(errors, []);
  console.log('Live search, desktop/phone accessibility, selection, real splat rendering, reload/reopen, empty/error recovery, built-in fallback, failed creation without writes, and Escape/focus passed.');
} finally { await browser.close(); }
